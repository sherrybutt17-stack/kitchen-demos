#!/usr/bin/env python3
"""
Generate three self-contained deploy repos from the three source sites.

    python3 scripts/split.py                 # github.io URLs, no CNAME
    python3 scripts/split.py example.com     # writes CNAME + real canonicals

GitHub Pages allows one custom domain per repository, so three subdomains means
three repos. Rather than forking the sources three ways — which would let the
design systems drift apart, the one thing CLAUDE.md forbids — this GENERATES the
deploy repos from site-*/ every run. site-*/ stays the only place you edit, the
same way dist/ is generated by build.py and never hand-edited.

Per repo the layout flattens by one level, because the site has to sit at the
repo root for Pages to serve it at the domain root:

    site-1-northstone/index.html   ->  northstone/index.html
    assets/media/img/n-*.webp      ->  northstone/assets/media/img/n-*.webp

so every "../assets/media/..." in the HTML becomes "assets/media/...". CSS and JS
carry no media references at all (verified), so they copy untouched.

Media is copied by scanning the HTML for literal references, so each repo gets
only the files it actually uses — 17-22 MB instead of the 95 MB shared pool.
"""

import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_ROOT = os.path.join(ROOT, "repos")

# source dir -> (repo name, subdomain label, placeholder domain to replace, brand)
SITES = [
    ("site-1-northstone",    "northstone",    "northstone",   "northstone.example",       "NORTHSTONE"),
    ("site-2-hearth-hollis", "hearth-hollis", "hearthhollis", "hearthandhollis.example",  "HEARTH & HOLLIS"),
    ("site-3-obsidian",      "obsidian",      "obsidian",     "obsidian.example",         "OBSIDIAN"),
]

GH_USER = "sherrybutt17-stack"


def referenced_media(html_texts):
    """Every img/video file the pages actually name, including srcset variants."""
    img, vid = set(), set()
    for t in html_texts:
        img.update(re.findall(r'\.\./assets/media/img/([A-Za-z0-9._-]+)', t))
        vid.update(re.findall(r'\.\./assets/media/video/([A-Za-z0-9._-]+)', t))
    return img, vid


def build_repo(src_dir, repo, sub, placeholder, brand, domain):
    sdir = os.path.join(ROOT, src_dir)
    out = os.path.join(OUT_ROOT, repo)
    # Regenerated from scratch, but never blow away the .git dir if one exists —
    # these are real repos with remotes and history once they have been pushed.
    if os.path.isdir(out):
        for entry in os.listdir(out):
            if entry == ".git":
                continue
            p = os.path.join(out, entry)
            shutil.rmtree(p) if os.path.isdir(p) else os.remove(p)
    os.makedirs(out, exist_ok=True)

    host = f"{sub}.{domain}" if domain else f"{GH_USER}.github.io/{repo}"
    site_url = f"https://{host}/"

    pages = sorted(p for p in os.listdir(sdir) if p.endswith(".html"))
    texts = [open(os.path.join(sdir, p), encoding="utf8").read() for p in pages]

    # ---- media (scan the ORIGINAL text, before the path rewrite) ----
    img, vid = referenced_media(texts)
    for kind, names in (("img", img), ("video", vid)):
        dst = os.path.join(out, "assets", "media", kind)
        os.makedirs(dst, exist_ok=True)
        for n in sorted(names):
            src = os.path.join(ROOT, "assets", "media", kind, n)
            if os.path.exists(src):
                shutil.copy2(src, os.path.join(dst, n))

    # ---- pages ----
    for name, html in zip(pages, texts):
        # str.replace, not re.sub — these strings contain no regex metacharacters
        # and CLAUDE.md's backslash trap only bites on the substitution side.
        html = html.replace("../assets/media/", "assets/media/")
        html = html.replace(f"https://{placeholder}/", site_url)
        html = html.replace(placeholder, host)
        open(os.path.join(out, name), "w", encoding="utf8").write(html)

    # ---- css / js / llms.txt (no media refs, copied verbatim) ----
    for sub_dir in ("css", "js"):
        s = os.path.join(sdir, "assets", sub_dir)
        if os.path.isdir(s):
            shutil.copytree(s, os.path.join(out, "assets", sub_dir))
    lt = os.path.join(sdir, "llms.txt")
    if os.path.exists(lt):
        txt = open(lt, encoding="utf8").read().replace(placeholder, host)
        open(os.path.join(out, "llms.txt"), "w", encoding="utf8").write(txt)

    # ---- Pages plumbing ----
    open(os.path.join(out, ".nojekyll"), "w").close()
    if domain:
        open(os.path.join(out, "CNAME"), "w").write(host + "\n")
    open(os.path.join(out, ".gitignore"), "w").write(".DS_Store\n")
    open(os.path.join(out, "README.md"), "w", encoding="utf8").write(
        f"# {brand}\n\n"
        f"Live: <https://{host}/>\n\n"
        f"**Generated — do not edit this repo by hand.** It is produced from\n"
        f"`{src_dir}/` in the main project by `scripts/split.py`, and every file here\n"
        f"is overwritten on the next run. Edit the source site, then re-run the split\n"
        f"and push.\n"
    )

    n_files = sum(len(f) for _, _, f in os.walk(out) if ".git" not in _)
    size = sum(os.path.getsize(os.path.join(dp, f))
               for dp, _, fs in os.walk(out) if ".git" not in dp for f in fs)
    print(f"  {repo:<15} {host:<38} {len(pages)} pages  "
          f"{len(img):2d} img  {len(vid)} vid  {size/1e6:5.1f} MB")
    return size


def main():
    domain = sys.argv[1].strip().lstrip(".") if len(sys.argv) > 1 else ""
    if domain.startswith("http"):
        domain = re.sub(r"^https?://", "", domain).rstrip("/")
    os.makedirs(OUT_ROOT, exist_ok=True)
    print(f"\nSplitting into repos/  {'domain: ' + domain if domain else '(no domain — github.io URLs, no CNAME)'}\n")
    total = sum(build_repo(*s, domain) for s in SITES)
    print(f"\n=== {total/1e6:.1f} MB across 3 repos (source pool is 95 MB)")
    if not domain:
        print("Re-run with your domain to write CNAME files: python3 scripts/split.py example.com")


if __name__ == "__main__":
    main()
